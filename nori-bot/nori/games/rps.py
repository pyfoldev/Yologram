CHOICES = ("камень", "ножницы", "бумага")
_BEATS = {"камень": "ножницы", "ножницы": "бумага", "бумага": "камень"}
ICONS = {"камень": "✊", "ножницы": "✌️", "бумага": "🖐"}


def judge(a: str, b: str) -> int:
    """1 — побеждает a, -1 — b, 0 — ничья."""
    if a == b:
        return 0
    return 1 if _BEATS[a] == b else -1
